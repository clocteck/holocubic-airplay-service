static void aes_expand_key(const uint8_t key[16], uint8_t round_key[176])
{
    static const uint8_t rcon[10] = {0x01,0x02,0x04,0x08,0x10,0x20,0x40,0x80,0x1b,0x36};
    unsigned generated = 16, r = 0, i;
    bytes_copy(round_key, key, 16);
    while (generated < 176) {
        uint8_t t[4];
        for (i = 0; i < 4; ++i) t[i] = round_key[generated - 4u + i];
        if ((generated & 15u) == 0) {
            uint8_t q = t[0]; t[0] = AES_SBOX[t[1]] ^ rcon[r++];
            t[1] = AES_SBOX[t[2]]; t[2] = AES_SBOX[t[3]]; t[3] = AES_SBOX[q];
        }
        for (i = 0; i < 4; ++i) {
            round_key[generated] = round_key[generated - 16u] ^ t[i]; generated++;
        }
    }
}

static void aes_inv_shift_rows(uint8_t s[16])
{
    uint8_t t;
    t=s[13]; s[13]=s[9]; s[9]=s[5]; s[5]=s[1]; s[1]=t;
    t=s[2]; s[2]=s[10]; s[10]=t; t=s[6]; s[6]=s[14]; s[14]=t;
    t=s[3]; s[3]=s[7]; s[7]=s[11]; s[11]=s[15]; s[15]=t;
}

static void aes_decrypt_block(const uint8_t input[16], uint8_t output[16], const uint8_t rk[176])
{
    uint8_t s[16];
    int round;
    unsigned i, c;
    for (i=0;i<16;++i) s[i]=input[i]^rk[160u+i];
    for (round=9;round>=1;--round) {
        aes_inv_shift_rows(s);
        for (i=0;i<16;++i) s[i]=AES_INV_SBOX[s[i]]^rk[(unsigned)round*16u+i];
        for (c=0;c<4;++c) {
            uint8_t *p=s+c*4u, a=p[0],b=p[1],d=p[2],e=p[3];
            p[0]=AES_INV_MUL[3][a]^AES_INV_MUL[1][b]^AES_INV_MUL[2][d]^AES_INV_MUL[0][e];
            p[1]=AES_INV_MUL[0][a]^AES_INV_MUL[3][b]^AES_INV_MUL[1][d]^AES_INV_MUL[2][e];
            p[2]=AES_INV_MUL[2][a]^AES_INV_MUL[0][b]^AES_INV_MUL[3][d]^AES_INV_MUL[1][e];
            p[3]=AES_INV_MUL[1][a]^AES_INV_MUL[2][b]^AES_INV_MUL[0][d]^AES_INV_MUL[3][e];
        }
    }
    aes_inv_shift_rows(s);
    for (i=0;i<16;++i) output[i]=AES_INV_SBOX[s[i]]^rk[i];
    bytes_zero(s,sizeof(s));
}

void airplay_aes128_cbc_decrypt(const uint8_t key[16],
                                const uint8_t iv[16],
                                const uint8_t *input,
                                uint8_t *output,
                                size_t len)
{
    airplay_aes128_context_t ctx;
    if (!key || !iv || !input || !output || (len & 15u)) return;
    airplay_aes128_init(&ctx, key);
    airplay_aes128_cbc_decrypt_ctx(&ctx, iv, input, output, len);
    bytes_zero(&ctx, sizeof(ctx));
}

void airplay_aes128_init(airplay_aes128_context_t *ctx, const uint8_t key[16])
{
    if (!ctx || !key) return;
    aes_expand_key(key, ctx->round_key);
}

void airplay_aes128_cbc_decrypt_ctx(const airplay_aes128_context_t *ctx,
                                    const uint8_t iv[16],
                                    const uint8_t *input,
                                    uint8_t *output,
                                    size_t len)
{
    uint8_t previous[16], block[16];
    size_t pos, i;
    if (!ctx || !iv || !input || !output || (len & 15u)) return;
    bytes_copy(previous, iv, 16);
    for (pos=0;pos<len;pos+=16) {
        aes_decrypt_block(input+pos,block,ctx->round_key);
        for(i=0;i<16;++i) output[pos+i]=block[i]^previous[i];
        bytes_copy(previous,input+pos,16);
    }
    bytes_zero(previous,sizeof(previous)); bytes_zero(block,sizeof(block));
}
