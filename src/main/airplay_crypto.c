static void bytes_zero(void *dst, size_t n)
{
    uint8_t *p = (uint8_t *)dst;
    while (n--) *p++ = 0;
}

static void bytes_copy(void *dst, const void *src, size_t n)
{
    uint8_t *d = (uint8_t *)dst;
    const uint8_t *s = (const uint8_t *)src;
    while (n--) *d++ = *s++;
}

static int limbs_ge(const uint32_t *a, const uint32_t *b)
{
    size_t i = RSA_LIMBS;
    while (i--) {
        if (a[i] > b[i]) return 1;
        if (a[i] < b[i]) return 0;
    }
    return 1;
}

static void limbs_sub(uint32_t *a, const uint32_t *b)
{
    uint64_t borrow = 0;
    size_t i;
    for (i = 0; i < RSA_LIMBS; ++i) {
        uint64_t bi = (uint64_t)b[i] + borrow;
        uint64_t ai = a[i];
        a[i] = (uint32_t)(ai - bi);
        borrow = (ai < bi) ? 1u : 0u;
    }
}

/* Coarsely integrated operand-scanning Montgomery multiplication. */
static void montgomery_mul(uint32_t out[RSA_LIMBS],
                           const uint32_t a[RSA_LIMBS],
                           const uint32_t b[RSA_LIMBS])
{
    uint32_t t[RSA_LIMBS + 1u];
    size_t i;
    bytes_zero(t, sizeof(t));

    for (i = 0; i < RSA_LIMBS; ++i) {
        uint64_t carry = 0;
        uint64_t z;
        uint32_t high;
        uint32_t m;
        size_t j;

        for (j = 0; j < RSA_LIMBS; ++j) {
            z = (uint64_t)t[j] + (uint64_t)a[j] * b[i] + carry;
            t[j] = (uint32_t)z;
            carry = z >> 32;
        }
        z = (uint64_t)t[RSA_LIMBS] + carry;
        t[RSA_LIMBS] = (uint32_t)z;
        high = (uint32_t)(z >> 32);

        m = t[0] * RSA_N0_INV;
        carry = 0;
        for (j = 0; j < RSA_LIMBS; ++j) {
            z = (uint64_t)t[j] + (uint64_t)m * RSA_N[j] + carry;
            if (j != 0) t[j - 1u] = (uint32_t)z;
            carry = z >> 32;
        }
        z = (uint64_t)t[RSA_LIMBS] + carry;
        t[RSA_LIMBS - 1u] = (uint32_t)z;
        t[RSA_LIMBS] = high + (uint32_t)(z >> 32);
    }

    if (t[RSA_LIMBS] || limbs_ge(t, RSA_N)) limbs_sub(t, RSA_N);
    for (i = 0; i < RSA_LIMBS; ++i) out[i] = t[i];
    bytes_zero(t, sizeof(t));
}

static void rsa_private_operation(const uint8_t input[AIRPLAY_RSA_BYTES],
                                  uint8_t output[AIRPLAY_RSA_BYTES])
{
    uint32_t x[RSA_LIMBS];
    uint32_t y[RSA_LIMBS];
    uint32_t tmp[RSA_LIMBS];
    uint32_t one[RSA_LIMBS];
    int bit;
    size_t i;

    bytes_zero(x, sizeof(x));
    bytes_zero(one, sizeof(one));
    one[0] = 1u;
    for (i = 0; i < AIRPLAY_RSA_BYTES; ++i) {
        size_t from_end = AIRPLAY_RSA_BYTES - 1u - i;
        x[i >> 2] |= (uint32_t)input[from_end] << ((i & 3u) * 8u);
    }

    montgomery_mul(tmp, x, RSA_R2);
    montgomery_mul(y, one, RSA_R2);
    for (bit = 2047; bit >= 0; --bit) {
        montgomery_mul(x, y, y);
        if ((RSA_D[(unsigned)bit >> 5] >> ((unsigned)bit & 31u)) & 1u) {
            montgomery_mul(y, x, tmp);
        } else {
            bytes_copy(y, x, sizeof(y));
        }
    }
    montgomery_mul(x, y, one);

    for (i = 0; i < AIRPLAY_RSA_BYTES; ++i) {
        output[AIRPLAY_RSA_BYTES - 1u - i] = (uint8_t)(x[i >> 2] >> ((i & 3u) * 8u));
    }
    bytes_zero(x, sizeof(x));
    bytes_zero(y, sizeof(y));
    bytes_zero(tmp, sizeof(tmp));
}

typedef struct sha1_ctx_t {
    uint32_t h[5];
    uint64_t total;
    uint8_t block[64];
    size_t used;
} sha1_ctx_t;

static uint32_t rol32(uint32_t v, unsigned n)
{
    return (v << n) | (v >> (32u - n));
}

static void sha1_transform(sha1_ctx_t *ctx, const uint8_t block[64])
{
    uint32_t w[80];
    uint32_t a, b, c, d, e;
    unsigned i;
    for (i = 0; i < 16; ++i) {
        const uint8_t *p = block + i * 4u;
        w[i] = ((uint32_t)p[0] << 24) | ((uint32_t)p[1] << 16) |
               ((uint32_t)p[2] << 8) | p[3];
    }
    for (i = 16; i < 80; ++i) w[i] = rol32(w[i - 3] ^ w[i - 8] ^ w[i - 14] ^ w[i - 16], 1);
    a = ctx->h[0]; b = ctx->h[1]; c = ctx->h[2]; d = ctx->h[3]; e = ctx->h[4];
    for (i = 0; i < 80; ++i) {
        uint32_t f, k, t;
        if (i < 20) { f = (b & c) | ((~b) & d); k = 0x5a827999u; }
        else if (i < 40) { f = b ^ c ^ d; k = 0x6ed9eba1u; }
        else if (i < 60) { f = (b & c) | (b & d) | (c & d); k = 0x8f1bbcdcu; }
        else { f = b ^ c ^ d; k = 0xca62c1d6u; }
        t = rol32(a, 5) + f + e + k + w[i];
        e = d; d = c; c = rol32(b, 30); b = a; a = t;
    }
    ctx->h[0] += a; ctx->h[1] += b; ctx->h[2] += c; ctx->h[3] += d; ctx->h[4] += e;
    bytes_zero(w, sizeof(w));
}

static void sha1_init(sha1_ctx_t *ctx)
{
    ctx->h[0] = 0x67452301u; ctx->h[1] = 0xefcdab89u; ctx->h[2] = 0x98badcfeu;
    ctx->h[3] = 0x10325476u; ctx->h[4] = 0xc3d2e1f0u;
    ctx->total = 0; ctx->used = 0;
}

static void sha1_update(sha1_ctx_t *ctx, const uint8_t *data, size_t len)
{
    ctx->total += len;
    while (len) {
        size_t take = 64u - ctx->used;
        if (take > len) take = len;
        bytes_copy(ctx->block + ctx->used, data, take);
        ctx->used += take; data += take; len -= take;
        if (ctx->used == 64u) { sha1_transform(ctx, ctx->block); ctx->used = 0; }
    }
}

static void sha1_final(sha1_ctx_t *ctx, uint8_t digest[20])
{
    uint64_t bits = ctx->total * 8u;
    unsigned i;
    ctx->block[ctx->used++] = 0x80;
    if (ctx->used > 56u) {
        while (ctx->used < 64u) ctx->block[ctx->used++] = 0;
        sha1_transform(ctx, ctx->block); ctx->used = 0;
    }
    while (ctx->used < 56u) ctx->block[ctx->used++] = 0;
    for (i = 0; i < 8; ++i) ctx->block[63u - i] = (uint8_t)(bits >> (i * 8u));
    sha1_transform(ctx, ctx->block);
    for (i = 0; i < 5; ++i) {
        digest[i * 4u] = (uint8_t)(ctx->h[i] >> 24);
        digest[i * 4u + 1u] = (uint8_t)(ctx->h[i] >> 16);
        digest[i * 4u + 2u] = (uint8_t)(ctx->h[i] >> 8);
        digest[i * 4u + 3u] = (uint8_t)ctx->h[i];
    }
    bytes_zero(ctx, sizeof(*ctx));
}

void airplay_sha1(const uint8_t *data, size_t len, uint8_t digest[20])
{
    sha1_ctx_t ctx;
    sha1_init(&ctx);
    if (data && len) sha1_update(&ctx, data, len);
    sha1_final(&ctx, digest);
}

static void mgf1_sha1(const uint8_t *seed, size_t seed_len, uint8_t *out, size_t out_len)
{
    uint32_t counter = 0;
    size_t pos = 0;
    while (pos < out_len) {
        sha1_ctx_t ctx;
        uint8_t digest[20];
        uint8_t c[4];
        size_t take = out_len - pos;
        if (take > sizeof(digest)) take = sizeof(digest);
        c[0] = (uint8_t)(counter >> 24); c[1] = (uint8_t)(counter >> 16);
        c[2] = (uint8_t)(counter >> 8); c[3] = (uint8_t)counter;
        sha1_init(&ctx); sha1_update(&ctx, seed, seed_len); sha1_update(&ctx, c, sizeof(c)); sha1_final(&ctx, digest);
        bytes_copy(out + pos, digest, take);
        bytes_zero(digest, sizeof(digest));
        pos += take; counter++;
    }
}

int airplay_rsa_pkcs1_sign_raw(const uint8_t *data,
                               size_t len,
                               uint8_t output[AIRPLAY_RSA_BYTES])
{
    uint8_t em[AIRPLAY_RSA_BYTES];
    size_t pad;
    if (!data || !output || len > AIRPLAY_RSA_BYTES - 11u) return 0;
    pad = AIRPLAY_RSA_BYTES - len - 3u;
    em[0] = 0; em[1] = 1;
    {
        size_t i;
        for (i = 0; i < pad; ++i) em[2u + i] = 0xff;
    }
    em[2u + pad] = 0;
    bytes_copy(em + 3u + pad, data, len);
    rsa_private_operation(em, output);
    bytes_zero(em, sizeof(em));
    return 1;
}

int airplay_rsa_oaep_decrypt(const uint8_t cipher[AIRPLAY_RSA_BYTES],
                             uint8_t *output,
                             size_t output_capacity,
                             size_t *output_len)
{
    uint8_t em[AIRPLAY_RSA_BYTES];
    uint8_t seed[20];
    uint8_t db[235];
    uint8_t mask[235];
    uint8_t empty_hash[20];
    size_t i, pos;
    int ok = 1;
    if (!cipher || !output || !output_len) return 0;
    *output_len = 0;
    rsa_private_operation(cipher, em);
    if (em[0] != 0) ok = 0;
    mgf1_sha1(em + 21u, 235u, seed, sizeof(seed));
    for (i = 0; i < sizeof(seed); ++i) seed[i] ^= em[1u + i];
    mgf1_sha1(seed, sizeof(seed), mask, sizeof(mask));
    for (i = 0; i < sizeof(db); ++i) db[i] = em[21u + i] ^ mask[i];
    airplay_sha1(NULL, 0, empty_hash);
    for (i = 0; i < sizeof(empty_hash); ++i) if (db[i] != empty_hash[i]) ok = 0;
    pos = sizeof(empty_hash);
    while (pos < sizeof(db) && db[pos] == 0) ++pos;
    if (pos >= sizeof(db) || db[pos] != 1) ok = 0;
    else ++pos;
    if (!ok || sizeof(db) - pos > output_capacity) {
        bytes_zero(em, sizeof(em)); bytes_zero(seed, sizeof(seed)); bytes_zero(db, sizeof(db));
        bytes_zero(mask, sizeof(mask)); return 0;
    }
    *output_len = sizeof(db) - pos;
    bytes_copy(output, db + pos, *output_len);
    bytes_zero(em, sizeof(em)); bytes_zero(seed, sizeof(seed)); bytes_zero(db, sizeof(db));
    bytes_zero(mask, sizeof(mask));
    return 1;
}

